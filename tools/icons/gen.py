rows = [l.split() for l in ICONS]

lu = json.load(open(lu_dir / "font/codepoints.json"))
css = (ph_dir / "src/regular/style.css").read_text()
ph = {m.group(1): int(m.group(2), 16)
      for m in re.finditer(r'\.ph\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"', css)}

def subset(src, out, cps):
    from fontTools.ttLib import TTFont
    from fontTools import subset as fts
    font = TTFont(str(src), lazy=True)
    # Lucide's GSUB (ligatures) does not parse under fonttools and icons are plain codepoints.
    for t in ("GSUB", "GPOS", "GDEF", "DSIG"):
        if t in font:
            del font[t]
    opts = fts.Options()
    opts.hinting = False
    opts.layout_features = []
    opts.name_IDs = ["*"]
    sub = fts.Subsetter(opts)
    sub.populate(unicodes=cps)
    sub.subset(font)
    font.save(str(out))

lu_cp = [lu[r[1]] for r in rows]
ph_cp = [ph[r[2]] for r in rows]
fonts = root / "crates/render/fonts"
subset(lu_dir / "font/lucide.ttf", fonts / "Lucide-subset.ttf", lu_cp)
subset(ph_dir / "src/regular/Phosphor.ttf", fonts / "Phosphor-subset.ttf", ph_cp)

