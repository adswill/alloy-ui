out.append("        }\n    }\n\n    /// The Lucide name, a handy label.\n    pub const fn name(self) -> &'static str {\n        match self {\n")
for r in rows:
    out.append(f"            Icon::{r[0]} => \"{r[1]}\",\n")
out.append("        }\n    }\n}\n")
(root / "crates/widgets/src/icon_data.rs").write_text("".join(out))
print(len(rows), "icons")
