#!/usr/bin/env python3
"""Regenerates crates/widgets/src/icon_names.rs: every icon name in the full Lucide and
Phosphor Regular packs with its codepoint, sorted for binary search.

Usage: names.py <lucide-static/package> <phosphor-web/package> <repo-root>
"""
import json, re, sys, pathlib

lu, ph, root = map(pathlib.Path, sys.argv[1:4])
lucide = json.loads((lu / "font/codepoints.json").read_text())
css = (ph / "src/regular/style.css").read_text()
phosphor = {m.group(1): int(m.group(2), 16)
            for m in re.finditer(r'\.ph\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"', css)}

def table(name, cfg, d):
    rows = ",\n".join(f'    ("{k}", 0x{v:X})' for k, v in sorted(d.items()))
    return f'#[cfg(feature = "{cfg}")]\npub(crate) static {name}: &[(&str, u32)] = &[\n{rows},\n];\n'

out = "//! Generated by tools/icons/names.py; do not edit.\n//! Every icon name in the full Lucide (ISC) and Phosphor Regular (MIT) packs.\n\n"
out += table("LUCIDE", "icons-lucide-full", lucide) + "\n" + table("PHOSPHOR", "icons-phosphor-full", phosphor)
(root / "crates/widgets/src/icon_names.rs").write_text(out)
print(len(lucide), "lucide,", len(phosphor), "phosphor")
